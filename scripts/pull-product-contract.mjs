#!/usr/bin/env node
/**
 * Refresh src/data/product-contract.json from the product repos.
 *
 * Personalization markers in MDX name real product facts:
 *
 *   <IfFeature id="awards">                → a feature id from web-api
 *   <IfSetting id="enable_speaker_acceptance"> → an Event boolean column
 *   [Open the builder](app:EventSessionForms) → a route id from web-ui-v2
 *
 * All three can be renamed by someone who will never open this repo, and a
 * stale marker fails silently: the block simply never satisfies, so a customer
 * who *does* have Awards is told they do not. The contract is committed so the
 * docs build can validate every marker with no network and no sibling
 * checkout, and this script is how it gets refreshed.
 *
 * Deliberately writes no timestamp — a generated-at field would make every
 * pull a diff and turn the CI freshness check into noise.
 *
 * Usage:
 *   npm run contract:pull
 *   SB_WEB_API_DIR=… SB_WEB_UI_V2_DIR=… npm run contract:pull
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WORKSPACE = resolve(DOCS_ROOT, '..');

const WEB_API_DIR = process.env.SB_WEB_API_DIR ?? join(WORKSPACE, 'sessionboard-web-api');
const WEB_UI_DIR = process.env.SB_WEB_UI_V2_DIR ?? join(WORKSPACE, 'sessionboard-web-ui-v2');

const OUT = join(DOCS_ROOT, 'src', 'data', 'product-contract.json');

/** The contract shape this repo's validator understands. */
const SUPPORTED_CONTRACT_VERSION = 2;

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

function readWebApiContract() {
  const script = join(WEB_API_DIR, 'scripts', 'export-product-contract.js');
  if (!existsSync(script)) {
    fail(
      `Cannot find ${script}.\n` +
        '  Check out sessionboard-web-api beside this repo, or set SB_WEB_API_DIR.',
    );
  }
  let stdout;
  try {
    stdout = execFileSync(process.execPath, [script], {
      cwd: WEB_API_DIR,
      env: { ...process.env, NODE_PATH: '.' },
      encoding: 'utf8',
      maxBuffer: 8 * 1024 * 1024,
    });
  } catch (err) {
    fail(
      `export-product-contract.js failed in ${WEB_API_DIR}.\n` +
        '  Run `npm install` there first — it loads the Event model to read the settings columns.\n' +
        `  ${err.stderr || err.message}`,
    );
  }
  const contract = JSON.parse(stdout);
  if (contract.contractVersion !== SUPPORTED_CONTRACT_VERSION) {
    fail(
      `web-api exports contractVersion ${contract.contractVersion} but this repo ` +
        `understands ${SUPPORTED_CONTRACT_VERSION}. Update scripts/check-markers.mjs ` +
        'and the marker spec before pulling.',
    );
  }
  return contract;
}

function readAppRoutes() {
  const file = join(WEB_UI_DIR, 'src', 'lib', 'appRoutes.json');
  if (!existsSync(file)) {
    fail(
      `Cannot find ${file}.\n` +
        '  Check out sessionboard-web-ui-v2 beside this repo, or set SB_WEB_UI_V2_DIR.',
    );
  }
  return JSON.parse(readFileSync(file, 'utf8'));
}

const api = readWebApiContract();
const appRoutes = readAppRoutes();

const contract = {
  '//':
    'GENERATED by scripts/pull-product-contract.mjs — do not hand-edit. ' +
    'Run `npm run contract:pull` with sessionboard-web-api and ' +
    'sessionboard-web-ui-v2 checked out beside this repo.',
  contractVersion: api.contractVersion,
  // Valid <IfFeature id> values. Always slugs — never the module UUIDs that
  // Sessions and Applications carry internally.
  features: api.features,
  // Which registry each slug lives in: event features, org features, or both.
  // Awards is org-only, so an event-only feature check would never satisfy it.
  featureScopes: api.featureScopes,
  // Per-scope resolution: slug → the id that scope's feature list carries.
  featureIdBySlug: api.featureIdBySlug,
  // Display names, so a collapsed block can say "Awards isn't enabled for
  // Acme Summit" rather than showing the reader a raw slug.
  featureNames: api.featureNames,
  // Valid <IfSetting id> values: boolean columns on the Event model.
  eventSettings: api.eventSettings,
  // Valid app: link targets.
  appRoutes,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${JSON.stringify(contract, null, 2)}\n`);

console.log(
  `Wrote ${OUT}\n` +
    `  ${contract.features.length} features\n` +
    `  ${contract.eventSettings.length} event settings\n` +
    `  ${Object.keys(appRoutes).length} app route targets`,
);
