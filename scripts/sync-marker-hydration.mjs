#!/usr/bin/env node
/**
 * Vendor the marker hydrator and its fixture corpus into sessionboard-web-ui-v2.
 *
 * The docs site and the in-product reader must render a conditional block
 * identically — same collapse, same wording, same "unknown means visible"
 * fallback. Two implementations of that would drift the first time either side
 * fixed a bug, and the failure is invisible: an article merely reads slightly
 * wrong on one surface.
 *
 * So there is one implementation, here, and the product repo gets a byte-exact
 * copy. `markerHydration.test.ts` there runs the shared corpus against its copy
 * and asserts the recorded checksums still match, so an edit to the vendored
 * file — or a change here that was never synced — fails on the consuming side.
 *
 * Usage:
 *   npm run markers:sync
 *   npm run markers:sync -- --check     # verify only, exit 1 on drift
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WORKSPACE = resolve(DOCS_ROOT, '..');
const WEB_UI_DIR = process.env.SB_WEB_UI_V2_DIR ?? join(WORKSPACE, 'sessionboard-web-ui-v2');

const CHECK_ONLY = process.argv.includes('--check');

const VENDOR_DIR = join(WEB_UI_DIR, 'src', 'lib', 'help');

const FILES = [
  {
    from: join(DOCS_ROOT, 'src', 'lib', 'marker-hydration.mjs'),
    to: join(VENDOR_DIR, 'markerHydration.mjs'),
    banner: true,
  },
  {
    from: join(DOCS_ROOT, 'tests', 'fixtures', 'marker-hydration.json'),
    to: join(VENDOR_DIR, 'markerHydration.fixtures.json'),
    banner: false,
  },
];

const CHECKSUMS = join(VENDOR_DIR, 'markerHydration.checksums.json');

const BANNER = `/**
 * VENDORED FILE — DO NOT EDIT HERE.
 *
 * Source of truth: sessionboard-docs/src/lib/marker-hydration.mjs
 * Refresh with:   cd ../sessionboard-docs && npm run markers:sync
 *
 * Edit the source, re-run the sync, and commit both repos. markerHydration.test.ts
 * fails if this copy and its recorded checksum disagree.
 */
`;

const sha = (text) => createHash('sha256').update(text).digest('hex');

if (!existsSync(WEB_UI_DIR)) {
  console.error(
    `\n✖ Cannot find ${WEB_UI_DIR}.\n` +
      '  Check out sessionboard-web-ui-v2 beside this repo, or set SB_WEB_UI_V2_DIR.\n',
  );
  process.exit(1);
}

const checksums = { specVersion: null, files: {} };
const drift = [];

for (const file of FILES) {
  const source = readFileSync(file.from, 'utf8');
  const payload = file.banner ? `${BANNER}\n${source}` : source;

  // Checksum the SOURCE, not the bannered payload, so the recorded value is
  // comparable across repos regardless of the banner text.
  checksums.files[file.to.replace(`${WEB_UI_DIR}/`, '')] = sha(source);

  if (CHECK_ONLY) {
    if (!existsSync(file.to)) {
      drift.push(`${file.to} is missing`);
      continue;
    }
    const current = readFileSync(file.to, 'utf8');
    if (current !== payload) drift.push(`${file.to} differs from the source`);
    continue;
  }

  mkdirSync(dirname(file.to), { recursive: true });
  writeFileSync(file.to, payload);
}

const specVersion = JSON.parse(
  readFileSync(join(DOCS_ROOT, 'tests', 'fixtures', 'marker-hydration.json'), 'utf8'),
).specVersion;
checksums.specVersion = specVersion;

const checksumJson = `${JSON.stringify(
  {
    '//':
      'GENERATED by sessionboard-docs/scripts/sync-marker-hydration.mjs. ' +
      'markerHydration.test.ts asserts the vendored files still hash to these values.',
    ...checksums,
  },
  null,
  2,
)}\n`;

if (CHECK_ONLY) {
  if (existsSync(CHECKSUMS)) {
    if (readFileSync(CHECKSUMS, 'utf8') !== checksumJson) {
      drift.push(`${CHECKSUMS} is stale`);
    }
  } else {
    drift.push(`${CHECKSUMS} is missing`);
  }

  if (drift.length > 0) {
    console.error(
      '\n✖ Vendored marker hydration is out of sync:\n' +
        drift.map((d) => `  - ${d}`).join('\n') +
        '\n\n  Run `npm run markers:sync` and commit both repos.\n',
    );
    process.exit(1);
  }
  console.log('✓ Vendored marker hydration matches the source.');
  process.exit(0);
}

writeFileSync(CHECKSUMS, checksumJson);

console.log(
  `Synced marker spec v${specVersion} into ${VENDOR_DIR}\n` +
    FILES.map((f) => `  ${f.to.replace(`${WEB_UI_DIR}/`, '')}`).join('\n'),
);
