#!/usr/bin/env node
/**
 * Writes one Skills article per skill: src/content/docs/skills/<id>.mdx, from
 * public/skills/downloads/skills.json (written by sessionboard-mcp-server's
 * `npm run skills:package -- --out ../sessionboard-docs/public/skills/downloads`).
 *
 *   npm run skills:pages            write the articles (and delete ones whose skill is gone)
 *   npm run skills:pages -- --check fail if any article is stale (CI)
 *
 * The articles are generated: change the skill or its catalog entry in the MCP repo,
 * re-package, re-run this. Hand-written pages (index, install, permissions) are kept.
 */
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const MANIFEST = 'public/skills/downloads/skills.json';
const DIR = 'src/content/docs/skills';
const HAND_WRITTEN = new Set(['index.mdx', 'install.mdx', 'permissions.mdx']);
const TITLE_SOFT_MAX = 48;
const check = process.argv.includes('--check');

/** Text safe inside MDX prose: no JSX braces or tags. */
const esc = (s) => String(s).replace(/[{}<>]/g, (c) => ({ '{': '&#123;', '}': '&#125;', '<': '&lt;', '>': '&gt;' })[c]);
const yaml = (s) => JSON.stringify(String(s));

function page(s) {
  const lines = [];
  const push = (...l) => lines.push(...l);
  push('---', `title: ${yaml(s.title)}`, `description: ${yaml(s.summary)}`);
  if (s.title.length > TITLE_SOFT_MAX) push('sidebar:', `  label: ${yaml(s.title.slice(0, TITLE_SOFT_MAX).replace(/\s+\S*$/, ''))}`);
  push('---', '');
  push(`{/* Generated by \`npm run skills:pages\` from ${MANIFEST}. Edit the skill in lennd/sessionboard-mcp-server, not this file. */}`);
  push('');
  push("import { Note } from '@compat';");
  push("import SkillActions from '../../../components/skills/SkillActions.astro';");
  push('');
  push(`${esc(s.summary)}`, '');
  push(`<SkillActions id="${s.id}" />`, '');
  if (s.connector === 'attend') {
    push('<Note>', 'This skill is for **attendees**. It runs on the attendee connection for one event, which the organizer switches on per event, and it only reads. See [Use the event app with AI assistants](/attend/ai-assistants).', '</Note>', '');
  }

  push('## How it works', '');
  s.steps.forEach((step, i) => push(`${i + 1}. ${esc(step)}`));
  push('');

  push('## Where it stops for you', '');
  if (s.pauses.length) {
    push('It stops and asks you in the conversation:', '');
    for (const p of s.pauses) push(`- ${esc(p)}`);
    push('');
  } else {
    push('Nothing to approve: this skill only reads.', '');
  }
  if (s.waitsInSessionboard.length) {
    push('These wait for a person to approve them in Sessionboard, even after you say yes in the chat. The assistant gives you the link and stops:', '');
    for (const p of s.waitsInSessionboard) push(`- ${esc(p)}`);
    push('');
  }

  push('## What you need', '');
  push(`- ${esc(s.permissions)}`);
  push(`- The Sessionboard connector, signed in as you. It needs ${s.scopes.map((x) => `\`${x}\``).join(', ')}${s.writes ? '; the write scopes only for the steps that change something' : ''}. [Install skills](/skills/install) covers connecting.`);
  push('- Everything runs as you: the assistant sees and changes only what your role allows. See [Permissions and control](/skills/permissions).');
  push('');

  push('## Try asking', '');
  for (const p of s.prompts) push(`- *"${esc(p)}"*`);
  push('');

  push('## Tools it uses', '');
  // A list, not a table: Starlight tables scroll sideways on phones without being focusable (axe scrollable-region-focusable).
  for (const t of s.tools) push(`- \`${t.name}\`: ${esc(t.title)} (${t.access === 'write' ? 'changes data' : 'reads'})`);
  push('');

  if (s.gaps.length) {
    push('## What it does not do yet', '');
    for (const g of s.gaps) push(`- ${esc(g)}`);
    push('');
  }

  push('## The full instructions', '');
  push(`This is the \`SKILL.md\` inside the download. Paste it into a ChatGPT project's instructions, or any assistant that does not install skills.`, '');
  push('<details class="sb-accordion">', '<summary>Show the instructions</summary>', '<div class="sb-accordion-body">', '');
  push('~~~~markdown', s.instructions.replace(/~~~~/g, '~~~'), '~~~~', '');
  push('</div>', '</details>', '');
  return lines.join('\n');
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
if (!existsSync(DIR)) mkdirSync(DIR, { recursive: true });
const want = new Map(manifest.skills.map((s) => [`${s.id}.mdx`, page(s)]));
const stale = [];
for (const [file, text] of want) {
  const p = join(DIR, file);
  const have = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (have !== text) {
    stale.push(file);
    if (!check) writeFileSync(p, text);
  }
}
for (const file of readdirSync(DIR)) {
  if (file.endsWith('.mdx') && !HAND_WRITTEN.has(file) && !want.has(file)) {
    stale.push(`${file} (no such skill)`);
    if (!check) unlinkSync(join(DIR, file));
  }
}
if (check && stale.length) {
  console.error(`Skills articles out of date (run npm run skills:pages):\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(check ? `skills pages current (${want.size})` : `wrote ${stale.length} of ${want.size} skills pages`);
